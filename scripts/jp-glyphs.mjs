// Scans src/ for CJK glyphs and writes src/lib/jp.ts (used for the Noto Serif JP subset request).
import fs from "node:fs";
import path from "node:path";
const root = path.join(process.cwd(), "src");
const set = new Set();
const walk = (d) => {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, f.name);
    if (f.isDirectory()) walk(p);
    else if (/\.(tsx?|css)$/.test(f.name) && f.name !== "jp.ts") {
      for (const ch of fs.readFileSync(p, "utf8")) {
        if (/[\u3000-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uff00-\uffef]/.test(ch)) set.add(ch);
      }
    }
  }
};
walk(root);
const chars = [...set].sort().join("");
fs.writeFileSync(
  path.join(root, "lib", "jp.ts"),
  `// AUTO-GENERATED by scripts/jp-glyphs.mjs — run \`pnpm jp\` after adding Japanese text.\nexport const JP_CHARS = ${JSON.stringify(chars)};\n`,
);
console.log(`jp.ts: ${set.size} glyphs → ${chars}`);
